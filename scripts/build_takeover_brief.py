    # carries a date within RECENT_DAYS of the newest dated heading, or that is marked 'Действующ'.
    recent = []
    if m:
        hist = h[m.start():]
        hs = list(re.finditer(r"^## [^\n]*", hist, re.M))
        def hdate(t):
            x = re.search(r"(\d{2})\.(\d{2})\.(20\d{2})", t) or re.search(r"(20\d{2})-(\d{2})-(\d{2})", t)
            if not x:
                return None
            a, b, c = x.groups()
            return datetime(int(c), int(b), int(a)) if len(a) == 2 else datetime(int(a), int(b), int(c))
        dates = [d for d in (hdate(x.group(0)) for x in hs) if d]
        newest = max(dates) if dates else None
        for i, x in enumerate(hs):
            body = hist[x.start(): hs[i + 1].start() if i + 1 < len(hs) else len(hist)]
            d = hdate(x.group(0))
            if re.search(r"Действующ", x.group(0)) or (d and newest and (newest - d).days <= RECENT_DAYS):
                recent.append(body)
    current_full = current + ("\n\n<!-- brief: recent sections below the history marker, verbatim -->\n\n" + "\n".join(recent) if recent else "")

