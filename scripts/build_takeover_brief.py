def sha(b):
    return hashlib.sha256(b).hexdigest()


def section(text, anchor_re):
    m = re.search(anchor_re, text, re.M)
    if not m:
        return None
    level = len(re.match(r"#+", text[m.start():]).group(0))
    nxt = re.compile(r"^#{1,%d} " % level, re.M).search(text, m.end())
    return text[m.start(): nxt.start() if nxt else len(text)]


def main(repo, out):
    repo, out = Path(repo), Path(out)
    out.mkdir(parents=True, exist_ok=True)
    texts, sources = {}, []
    for name, did in list(DOCS.items()) + [MASTER]:
        b = (repo / name).read_bytes()
        texts[name] = b.decode("utf-8-sig").replace("\r\n", "\n")
