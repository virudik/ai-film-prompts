const assert=require('node:assert/strict');
const {assess,safePath,PACKET_LAG_MIN}=require('../continue-status.js');
const files=['work-resume-register.json','reports/current-work-checkpoint.md','shadow/current-checkpoint.md','shadow/takeover-brief.json','ops/topview-launch-queue.json'];
const now=Date.now(), hashes=Object.fromEntries(files.map(p=>[p,'a'.repeat(64)]));
const p={schema_version:1,generator:'continue-2.0',ready_for_resume:true,execution_authorized:false,selected_work:{work_id:'x'},checked_at:new Date(now).toISOString(),sources:files.map(file=>({file,sha256:hashes[file]}))};
assert.equal(assess(p,hashes,now).ready,true);
assert.equal(assess(p,hashes,now).tone,'ready');
const lagging=assess(p,{},now);
assert.equal(lagging.ready,false);
assert.equal(lagging.tone,'pending','a fresh packet may lag the files it hashes');
const stuck=assess({...p,checked_at:new Date(now-(PACKET_LAG_MIN+5)*60000).toISOString()},{},now);
assert.equal(stuck.tone,'alarm','a hash miss older than the rebuild window is a real fault');
assert.equal(assess({...p,ready_for_resume:false},hashes,now).ready,false);
assert.equal(assess({...p,ready_for_resume:false},hashes,now).tone,'alarm');
assert.equal(assess({...p,execution_authorized:true},hashes,now).ready,false);
assert.equal(assess({...p,checked_at:new Date(now+3600000).toISOString()},hashes,now).ready,false);
assert.equal(assess({...p,sources:p.sources.slice(1)},hashes,now).ready,false);
assert.equal(assess(null,hashes,now).ready,false);
assert.equal(assess(null,hashes,now).tone,'alarm');
const idle={...p,ready_for_resume:false,selected_work:null};
const idleResult=assess(idle,hashes,now);
assert.equal(idleResult.ready,false);
assert.equal(idleResult.tone,'idle','no selected work is nothing to continue, not a warning');
assert.equal(assess(idle,{},now).tone,'idle','a hash miss on an idle packet is still not a warning');
assert.equal(assess({...idle,execution_authorized:true},hashes,now).tone,'alarm');
for(const s of ['../secret','https://evil.test/x','//evil','/absolute','a/../b'])assert.equal(safePath(s),false);
console.log('Continue indicator: ready, stale, missing, unsafe and future-time cases passed.');
const prefix='projects/raznoe/';
const pf=[prefix+'work-resume-register.json',prefix+'reports/current-work-checkpoint.md','shadow/current-checkpoint.md','shadow/takeover-brief.json',prefix+'ops/topview-launch-queue.json','projects/projects.json','projects/README.md',prefix+'HANDOFF.md',prefix+'INSTRUCTIONS.md',prefix+'project-status.json',prefix+'video-prompts.md'];
const ph=Object.fromEntries(pf.map(f=>[f,'b'.repeat(64)]));
const pp={...p,project:'raznoe',sources:pf.map(file=>({file,sha256:ph[file]}))};
assert.equal(assess(pp,ph,now,'raznoe').ready,true);
assert.equal(assess(pp,ph,now,'seregius').ready,false);
assert.equal(assess(p,hashes,now,'raznoe').ready,false);
assert.equal(assess({...pp,sources:pp.sources.filter(s=>s.file!==prefix+'HANDOFF.md')},ph,now,'raznoe').ready,false);
console.log('Project isolation, own source requirements and cross-project rejection passed.');
